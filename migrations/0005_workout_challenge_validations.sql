-- #421 — durable achievements and dynamic ownership for DISTANCE challenges.
-- DESIGN MIGRATION — DO NOT APPLY TO PRODUCTION before full implementation,
-- tests, database backup and explicit release approval.
--
-- Existing canonical identity, card ownership, ownership history, packs,
-- gifts, aliases and account authentication remain unchanged.
-- The owner is still workout_cards.owner_user_id, not a new inventory.
--
-- A successful attempt by an authenticated runner MAY immediately transfer
-- an already existing challenge card from its present owner to that runner.
-- The user does NOT have to own a card before undertaking its challenge.
-- Distinguish proof of sporting success from temporary possession.
-- Database statements for accepting an attempt, recording its first success,
-- and moving a card must execute atomically under one authoritative server.
-- Never trust client-submitted "success=true" or client-set ownership.
--
-- Local location tracks and private music tokens must never reach D1.
-- The proof stored here is an adjudicated activity result, NOT a cryptographic
-- attestation of real-world running. A GPS phone can be spoofed.
--
-- Individual attempt ledger: preserve failed and uncertain results as well as
-- verified successes. One unique id per attempt makes retries idempotent.
-- Account deletion anonymizes history (ON DELETE SET NULL) to respect privacy;
-- "permanent proof" is an in-app guarantee while the account exists, not an
-- irreversible record immune to legal account deletion.
CREATE TABLE IF NOT EXISTS workout_challenge_attempts (
  attempt_id TEXT PRIMARY KEY NOT NULL,
  share_id INTEGER NOT NULL REFERENCES workout_cards(share_id) ON DELETE CASCADE,
  user_id TEXT REFERENCES community_users(id) ON DELETE SET NULL,
  result TEXT NOT NULL CHECK(result IN ('won','lost','unverified')),
  completed_at INTEGER NOT NULL CHECK(completed_at>0),
  accepted_at INTEGER NOT NULL CHECK(accepted_at>0),
  goal_distance_m INTEGER NOT NULL CHECK(goal_distance_m>0),
  measured_distance_m INTEGER NOT NULL CHECK(measured_distance_m>=0),
  playlist_duration_sec INTEGER NOT NULL CHECK(playlist_duration_sec>0),
  elapsed_music_sec INTEGER NOT NULL CHECK(elapsed_music_sec>=0),
  CHECK(result <> 'won' OR (measured_distance_m>=goal_distance_m AND elapsed_music_sec<=playlist_duration_sec))
);
CREATE INDEX IF NOT EXISTS workout_challenge_attempts_by_runner
  ON workout_challenge_attempts(user_id,completed_at DESC);
CREATE INDEX IF NOT EXISTS workout_challenge_attempts_by_card
  ON workout_challenge_attempts(share_id,accepted_at DESC);

-- Permanent per-runner FIRST accepted win, one row per account per card.
-- Crucially, the runner does NOT need to own the card to validate its challenge.
-- Personal proof remains when the card is gifted or won by another person.
-- Public site count: SELECT COUNT(*) WHERE share_id=? (distinct winners,
-- not successful attempt count, and not former owner count).
CREATE TABLE IF NOT EXISTS workout_challenge_validations (
  user_id TEXT NOT NULL REFERENCES community_users(id) ON DELETE CASCADE,
  share_id INTEGER NOT NULL REFERENCES workout_cards(share_id) ON DELETE CASCADE,
  first_attempt_id TEXT NOT NULL UNIQUE REFERENCES workout_challenge_attempts(attempt_id),
  first_validated_at INTEGER NOT NULL CHECK(first_validated_at>0),
  PRIMARY KEY (user_id,share_id)
);
CREATE INDEX IF NOT EXISTS workout_challenge_validations_share
  ON workout_challenge_validations(share_id);

-- Bridge challenge-earned ownership to the exact attested attempt.
-- The actual owner and the existing workout_card_history trigger remain the
-- authority for ownership transfers. This ledger is NOT a second owner field.
-- Only one transfer event may be generated by a single attempt.
CREATE TABLE IF NOT EXISTS workout_challenge_transfers (
  attempt_id TEXT PRIMARY KEY REFERENCES workout_challenge_attempts(attempt_id),
  share_id INTEGER NOT NULL REFERENCES workout_cards(share_id) ON DELETE CASCADE,
  previous_owner_id TEXT REFERENCES community_users(id) ON DELETE SET NULL,
  new_owner_id TEXT REFERENCES community_users(id) ON DELETE SET NULL,
  transferred_at INTEGER NOT NULL CHECK(transferred_at>0)
);
CREATE INDEX IF NOT EXISTS workout_challenge_transfers_by_card
  ON workout_challenge_transfers(share_id,transferred_at DESC);

-- API implementation requirements (not created by this SQL):
-- 1. Server-authenticated runner and existing canonical card;
--    v2 distance challenge only, no time workouts.
-- 2. Verify outcome from a plausible full GPS/playback event sequence and
--    one unique unconsumed attempt; do not trust a boolean claim.
-- 3. Insert attempt and first-win proof, then atomically claim/update
--    workout_cards.owner_user_id with last_reason='challenge_win',
--    acquired_at=server time and pack_eligible=0.
-- 4. Existing workout_card_history_change trigger records old/new owner.
--    Associate attempt_id through workout_challenge_transfers.
-- 5. Gift flows MUST re-check owner at redemption (they already do):
--    a gift created before another runner wins can become unavailable.
-- 6. Keep a runner's validation and attempt history even after their card
--    passes to someone else; no color change for classic time workouts.
-- 7. Return private challengeValidated only in authenticated collection;
--    public APIs return counts and consent-appropriate aliases, never raw IDs.
-- 8. No client or website can upload an arbitrary state saying it won.
